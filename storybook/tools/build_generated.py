"""Build assets/js/generated.js: the logo paths, DESIGN.md, brand.md and tokens, embedded so the
site works offline and from file:// (fetch() is blocked there). Re-run after editing the kit:
    python tools/build_generated.py
"""
import json, os, re
SB = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
A = lambda *p: os.path.join(SB, "assets", *p)
read = lambda p: open(p, encoding="utf-8").read()

master = read(A("logo", "crossword-lockup.svg"))
paths = re.findall(r'<path d="([^"]+)"', master)
mark, word = paths[0], paths[1:]
def svg(vb, ds): return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{vb}" fill="currentColor">' + "".join(f'<path d="{d}"/>' for d in ds) + "</svg>"
logo = {
    "signature": svg("0 0 837 117", paths),
    "mark": svg("0 1.53 162.91 113.67", [mark]),
    "wordmark": svg("209.3 0 627.2 117", word),
}
glyphs = json.load(open(A("patterns", "badge-glyphs.json"), encoding="utf-8"))
out = {
    "GLYPHS": glyphs,
    "LOGO": logo,
    "DESIGN_MD": read(A("brand", "DESIGN.md")),
    "BRAND_MD": read(A("brand", "brand.md")),
    "THEME_CSS": read(A("brand", "theme.aliases.css")),
    "THEME_SEMANTIC_CSS": read(A("brand", "theme.css")).lstrip("﻿"),
    "MOTION_CSS": read(A("brand", "motion.css")),
    "DTCG": read(A("brand", "tokens.dtcg.json")).lstrip("﻿"),
}
js = "/* generated by tools/build_generated.py: do not edit by hand */\n" + "".join(f"window.{k}={json.dumps(v, ensure_ascii=False)};\n" for k, v in out.items())
open(A("js", "generated.js"), "w", encoding="utf-8").write(js)
print("wrote generated.js", len(js))
